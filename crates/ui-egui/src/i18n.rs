/// A track's name for display: the default names (`Video 1`, `Audio 2`) are shown in Japanese;
/// a name the user typed is shown as it is. The project keeps the stored name.
pub fn tr_track_name(name: &str) -> Cow<'_, str> {
    if !is_japanese() {
        return name.into();
    }
    for (en, ja) in [("Video ", "ビデオ "), ("Audio ", "オーディオ ")] {
        if let Some(n) = name.strip_prefix(en)
            && !n.is_empty()
            && n.bytes().all(|b| b.is_ascii_digit())
        {
            let shown = format!("{ja}{n}");
            remember(name, &shown);
            return shown.into();
        }
    }
    if name == "Mix" {
        return t("Mix", "ミックス").into();
    }
    name.into()
}

