//! Internationalization (i18n): the UI language and the English → Japanese dictionary.
//!
//! The source language is English. Text reaches the screen in one of two ways:
//! - [`t`] / [`tf!`](crate::tf) carry both languages at the call site (`t("Save", "保存")`);
//! - [`tr`] and its siblings look English text that comes from elsewhere (command labels, effect
//!   names, the settings schema) up in the dictionary.
//!
//! Automation ids and labels, command ids and everything stored in projects stay English whatever
//! the language is, so agents and files do not depend on it.

use std::borrow::Cow;
use std::collections::HashMap;
use std::sync::atomic::{AtomicU8, Ordering};
use std::sync::{OnceLock, PoisonError, RwLock};

/// The language of the user interface (Settings ▸ Appearance ▸ Language).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Language {
    Japanese,
    English,
}

impl Language {
    pub const ALL: [Language; 2] = [Language::Japanese, Language::English];
    /// The value stored in the preferences (`ja`, `en`).
    pub fn pref_name(self) -> &'static str {
        match self {
            Language::Japanese => "ja",
            Language::English => "en",
        }
    }
    /// The language of a Settings ▸ Appearance ▸ Language value. `auto` (and anything unknown)
    /// follows `system`, the operating system's language as a BCP 47 tag: Japanese on a Japanese
    /// system, English on any other, and Japanese when the system does not say.
    pub fn from_pref(s: &str, system: Option<&str>) -> Language {
        match s.trim().to_ascii_lowercase().as_str() {
            "en" | "english" => Language::English,
            "ja" | "japanese" => Language::Japanese,
            _ => match system.map(|t| t.trim().to_ascii_lowercase()) {
                Some(t) if !(t == "ja" || t.starts_with("ja-") || t.starts_with("ja_")) => Language::English,
                _ => Language::Japanese,
            },
        }
    }
    /// The language's own name, as shown in the language picker.
    pub fn native_name(self) -> &'static str {
        match self {
            Language::Japanese => "日本語",
            Language::English => "English",
        }
    }
}

static LANGUAGE: AtomicU8 = AtomicU8::new(0);

fn system() -> &'static RwLock<Option<String>> {
    static SYSTEM: OnceLock<RwLock<Option<String>>> = OnceLock::new();
    SYSTEM.get_or_init(Default::default)
}

/// Tell the UI the operating system's language (a BCP 47 tag such as `ja-JP`), which the `Auto`
/// language setting follows. The desktop app sets it at startup; this crate asks no OS itself.
pub fn set_system_language(tag: Option<String>) {
    *system().write().unwrap_or_else(PoisonError::into_inner) = tag;
}

/// The operating system's language, when the host told us ([`set_system_language`]).
pub fn system_language() -> Option<String> {
    system().read().unwrap_or_else(PoisonError::into_inner).clone()
}

/// The language text is shown in now.
pub fn language() -> Language {
    if LANGUAGE.load(Ordering::Relaxed) == 1 { Language::English } else { Language::Japanese }
}

/// Switch the language; takes effect from the next frame.
pub fn set_language(l: Language) {
    LANGUAGE.store(if l == Language::English { 1 } else { 0 }, Ordering::Relaxed);
}

pub fn is_japanese() -> bool {
    language() == Language::Japanese
}

/// `en` or `ja`, whichever the language is.
pub fn t(en: &'static str, ja: &'static str) -> &'static str {
    if is_japanese() {
        remember(en, ja);
        ja
    } else {
        en
    }
}

/// Japanese text that has been shown → the English it stands for. Filled by [`t`] and [`tr`] as
/// text is translated, read by [`english_of`].
fn shown() -> &'static RwLock<HashMap<String, String>> {
    static SHOWN: OnceLock<RwLock<HashMap<String, String>>> = OnceLock::new();
    SHOWN.get_or_init(Default::default)
}

pub(crate) fn remember(en: &str, ja: &str) {
    if en == ja || shown().read().unwrap_or_else(PoisonError::into_inner).contains_key(ja) {
        return;
    }
    shown().write().unwrap_or_else(PoisonError::into_inner).entry(ja.to_string()).or_insert_with(|| en.to_string());
}

/// The English of text shown in the UI language: automation labels are English in every language
/// (`crate::automation::Registry::add`), so agents read the same labels whatever the user chose.
/// Covers text that came from [`t`] or [`tr`], alone or put together from such parts
/// (`再生 (Space)`). Text that is not wholly made of them (a name the user typed) is returned
/// unchanged, never half translated.
pub fn english_of(label: &str) -> Cow<'_, str> {
    if label.is_ascii() {
        return label.into();
    }
    let map = shown().read().unwrap_or_else(PoisonError::into_inner);
    if let Some(en) = map.get(label) {
        return en.clone().into();
    }
    // composed labels are worked out once per label and vocabulary (this runs for every element
    // of every frame)
    static COMPOSED: OnceLock<RwLock<(usize, HashMap<String, Option<String>>)>> = OnceLock::new();
    let cache = COMPOSED.get_or_init(Default::default);
    {
        let c = cache.read().unwrap_or_else(PoisonError::into_inner);
        if c.0 == map.len()
            && let Some(known) = c.1.get(label)
        {
            return known.clone().map_or(label.into(), Cow::Owned);
        }
    }
    let en = compose_english(&map, label);
    let mut c = cache.write().unwrap_or_else(PoisonError::into_inner);
    if c.0 != map.len() || c.1.len() >= COMPOSED_MAX {
        *c = (map.len(), HashMap::new());
    }
    c.1.insert(label.to_string(), en.clone());
    en.map_or(label.into(), Cow::Owned)
}

/// Labels remembered by [`english_of`] before it starts over.
const COMPOSED_MAX: usize = 8192;

/// `label` in English when all of it is known text and plain ASCII, else None.
fn compose_english(map: &HashMap<String, String>, label: &str) -> Option<String> {
    // parts between separators: `Ctrl+Down (プログラム), Ctrl+Down (プロパティ)`
    let mut out = String::with_capacity(label.len());
    let mut rest = label;
    while !rest.is_empty() {
        let end = rest.find(PART_SEPARATORS).unwrap_or(rest.len());
        let (part, tail) = rest.split_at(end);
        out.push_str(map.get(part).map_or(part, String::as_str));
        let sep = tail.chars().next().map_or(0, char::len_utf8);
        let (sep, tail) = tail.split_at(sep);
        out.push_str(sep);
        rest = tail;
    }
    if out.is_ascii() {
        return Some(out);
    }
    // parts that hold a separator themselves (`1 フレーム戻る / Undo`): the longest known text at
    // each position
    let mut out = String::with_capacity(label.len());
    let mut rest = label;
    while let Some(c) = rest.chars().next() {
        match map.iter().filter(|(ja, _)| rest.starts_with(ja.as_str())).max_by_key(|(ja, _)| ja.len()) {
            Some((ja, en)) => {
                out.push_str(en);
                rest = rest.get(ja.len()..).unwrap_or_default();
            }
            None => {
                out.push(c);
                rest = rest.get(c.len_utf8()..).unwrap_or_default();
            }
        }
    }
    out.is_ascii().then_some(out)
}

/// What separates the parts of a composed label.
const PART_SEPARATORS: [char; 8] = [' ', '(', ')', ',', ':', '…', '/', '·'];

/// [`format!`] with an English and a Japanese format string and one set of arguments:
/// `tf!("Queue ({n})", "キュー ({n})")`.
#[macro_export]
macro_rules! tf {
    ($en:literal, $ja:literal $(, $($arg:tt)*)?) => {
        if $crate::i18n::is_japanese() { format!($ja $(, $($arg)*)?) } else { format!($en $(, $($arg)*)?) }
    };
}

/// Translate English text to the UI language; text the dictionary does not know is returned as it is.
pub fn tr(s: &str) -> &str {
    if !is_japanese() {
        return s;
    }
    let ja = tr_ja(s);
    remember(s, ja);
    ja
}

