/// Text that is shown as it is in Japanese too: units, numbers, measurements, brand and font
/// names. Used by the coverage test.
#[cfg(test)]
pub(crate) fn stays_ascii(s: &str) -> bool {
    const NAMES: &[&str] = &["Q", "RGB", "Inter", "JetBrains Mono", "Look", "Look LUT"];
    if NAMES.contains(&s) {
        return true;
    }
    // numbers with units: "1.25 kHz", "12 dB/oct", "100 IRE", "10%", "8"
    let rest = s.trim_start_matches(|c: char| c.is_ascii_digit() || c == '.' || c == ' ');
    rest.len() < s.len() && ["", "Hz", "kHz", "dB/oct", "IRE", "%"].contains(&rest)
}
