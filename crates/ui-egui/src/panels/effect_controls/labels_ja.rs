//! Japanese names for effect parameters and their dropdown choices (Effect Controls panel).
//!
//! Pure lookups that do not read the UI-language global, so they can be tested directly over the
//! effect catalog. `None` means "no Japanese for this text"; callers show the English then.

/// Japanese label of parameter `param` of effect `effect`, whose English label is `en`.
/// A few labels mean different things in different effects; those are told apart by
/// (effect, param) first, everything else by the English label.
pub(crate) fn param_label_ja(effect: &str, param: &str, en: &str) -> Option<&'static str> {
    let by_param = match (effect, param) {
        ("scientific_filter", "order") => Some("次数"),
        ("shape_dissolve", "order") => Some("順序"),
        _ => None,
    };
    by_param.or_else(|| label_ja(en))
}

